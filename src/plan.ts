import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { firstSentence, countTokens } from './tokens.js';
import { renderSkill } from './servers.js';
import type { ScanReport, StdioLaunch, UsageReport } from './types.js';

export interface DietPlans {
  hotSet: string[];
  dropped: string[];
  subsetSchemaTokens: number;
  baselineSchemaTokens: number;
  skill: string;
  skillTokens: number;
}

export function buildPlans(scan: ScanReport, usage: UsageReport): DietPlans {
  const byName = new Map(scan.servers.flatMap((server) => server.tools.map((tool) => [tool.name, tool] as const)));
  const hotSet = usage.used.filter((name) => byName.has(name));
  const dropped = [...byName.keys()].filter((name) => !hotSet.includes(name)).sort();
  const subsetSchemaTokens = hotSet.reduce((sum, name) => sum + (byName.get(name)?.tokens ?? 0), 0);
  const entries = hotSet.map((name) => {
    const tool = byName.get(name);
    return { name, summary: firstSentence(tool?.description ?? '') };
  });
  const skill = renderSkill(entries);
  return {
    hotSet,
    dropped,
    subsetSchemaTokens,
    baselineSchemaTokens: scan.schemaTokens,
    skill,
    skillTokens: countTokens(skill),
  };
}

export function renderDietCli(launch: StdioLaunch): string {
  const args = JSON.stringify(launch.args);
  const envExtra = JSON.stringify(launch.env ?? {});
  return `#!/usr/bin/env node
// Generated by mcp-diet. SPDX-License-Identifier: Apache-2.0
// Calls one tool on a stdio MCP server. Usage: node diet-cli.mjs <tool> '<json>'
import { Client } from '@modelcontextprotocol/client';
import { StdioClientTransport, getDefaultEnvironment } from '@modelcontextprotocol/client/stdio';

const tool = process.argv[2];
const argsJson = process.argv[3] ?? '{}';
if (!tool) {
  console.error('usage: diet-cli.mjs <tool> [json-args]');
  process.exit(2);
}
let toolArgs = {};
try {
  toolArgs = JSON.parse(argsJson);
} catch (error) {
  console.error('args are not JSON', error instanceof Error ? error.message : error);
  process.exit(2);
}
const client = new Client({ name: 'mcp-diet-cli', version: '0.1.0' });
const transport = new StdioClientTransport({
  command: ${JSON.stringify(launch.command)},
  args: ${args},
  cwd: process.cwd(),
  env: { ...getDefaultEnvironment(), ...${envExtra} },
  stderr: 'pipe',
});
await client.connect(transport);
try {
  const result = await client.callTool({ name: tool, arguments: toolArgs });
  process.stdout.write(JSON.stringify(result, null, 2) + '\\n');
  process.exit(result.isError ? 1 : 0);
} finally {
  await client.close();
}
`;
}

export async function writePlans(
  dir: string,
  plans: DietPlans,
  launch: StdioLaunch,
): Promise<void> {
  await mkdir(path.join(dir, 'cli-skill'), { recursive: true });
  await mkdir(path.join(dir, 'lazy'), { recursive: true });
  const allowlist = {
    diet: 'subset',
    tools: plans.hotSet,
    dropped: plans.dropped,
    subsetSchemaTokens: plans.subsetSchemaTokens,
    baselineSchemaTokens: plans.baselineSchemaTokens,
  };
  await writeFile(path.join(dir, 'allowlist.json'), `${JSON.stringify(allowlist, null, 2)}\n`);
  const subsetConfig = {
    mcpServers: {
      'kitchen-sink-subset': {
        command: launch.command,
        args: launch.args,
        env: { ...(launch.env ?? {}), MCP_DIET_ALLOWLIST: plans.hotSet.join(',') },
      },
    },
  };
  await writeFile(path.join(dir, 'subset.mcp.json'), `${JSON.stringify(subsetConfig, null, 2)}\n`);
  await writeFile(path.join(dir, 'cli-skill', 'SKILL.md'), plans.skill);
  await writeFile(path.join(dir, 'cli-skill', 'diet-cli.mjs'), renderDietCli(launch));
  const lazyConfig = {
    mcpServers: {
      'kitchen-sink-lazy': {
        note: 'In-process lazy server used by the A/B harness. Standing tools are diet_search and diet_call.',
        tools: ['diet_search', 'diet_call'],
      },
    },
  };
  await writeFile(path.join(dir, 'lazy', 'surface.json'), `${JSON.stringify(lazyConfig, null, 2)}\n`);
  const readme = [
    '# Generated diet plans',
    '',
    'Regenerate with `npm run demo`. These files are derived from the scan and the trace file.',
    '',
    `- Hot set: ${plans.hotSet.length} tools`,
    `- Dropped: ${plans.dropped.length} tools`,
    `- Subset schema tokens (sum of scanned tool JSON): ${plans.subsetSchemaTokens}`,
    `- Skill tokens (o200k_base): ${plans.skillTokens}`,
    '',
    'subset.mcp.json launches the mock server with MCP_DIET_ALLOWLIST.',
    'cli-skill/SKILL.md is the instruction block mounted with the single diet_exec tool.',
    'cli-skill/diet-cli.mjs is the shell wrapper.',
    'lazy/surface.json names the two meta-tools. The harness serves them in-process.',
    '',
  ].join('\n');
  await writeFile(path.join(dir, 'README.md'), readme);
}
